// Builds the coastline path for the Atlas of Revelation from Natural Earth (world-atlas, public domain).
// Output: src/components/connections/atlasLand.ts (an SVG path in the atlas's own coordinates).
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'
import { geoClipRectangle, geoPath, geoTransform } from 'd3-geo'

export const BOX = { lon0: 8, lon1: 56, lat0: 22, lat1: 46 }
const K = 1000 / ((BOX.lon1 - BOX.lon0) * Math.cos((34 * Math.PI) / 180))
const project = (lon, lat) => [(lon - BOX.lon0) * K * Math.cos((34 * Math.PI) / 180), (BOX.lat1 - lat) * K]
const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-50m.json', import.meta.url)))
const land = feature(topo, topo.objects.land)
const H = Math.round((BOX.lat1 - BOX.lat0) * K)
// Project, drop points closer than 1.2 units to the last kept one, then clip to the frame.
let last = null
const tr = geoTransform({
  point(lon, lat) {
    const [x, y] = project(lon, lat)
    if (last && Math.hypot(x - last[0], y - last[1]) < 1.2) return
    last = [x, y]
    this.stream.point(Math.round(x), Math.round(y))
  },
  lineStart() {
    last = null
    this.stream.lineStart()
  },
})
const clip = geoClipRectangle(-10, -10, 1010, H + 10)
const pipeline = { stream: (s) => tr.stream(clip(s)) }
// Clip in lon/lat first (with a margin) so the path stays small.
const clipped = {
  type: 'FeatureCollection',
  features: land.features.map((f) => ({
    ...f,
    geometry: {
      type: 'MultiPolygon',
      coordinates: (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates).filter((poly) =>
        poly[0].some(([lon, lat]) => lon > BOX.lon0 - 6 && lon < BOX.lon1 + 6 && lat > BOX.lat0 - 6 && lat < BOX.lat1 + 6),
      ),
    },
  })),
}
const d = geoPath(pipeline)(clipped)
writeFileSync(
  new URL('../src/components/connections/atlasLand.ts', import.meta.url),
  `// Generated by scripts/build-atlas-map.mjs from Natural Earth 1:50m land (public domain). Do not edit.\nexport const ATLAS_W = 1000\nexport const ATLAS_H = ${H}\nexport const ATLAS_K = ${K}\nexport const ATLAS_BOX = ${JSON.stringify(BOX)}\nexport const LAND = ${JSON.stringify(d)}\n`,
)
console.log('path length', d.length, 'H', H)
